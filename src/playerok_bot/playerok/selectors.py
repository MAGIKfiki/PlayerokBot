"""Селектори для сторінок Playerok, потрібні для читання замовлень.

Де можливо, використовуються стабільні атрибути (префікси href, ARIA role) —
вони не залежать від верстки чи порядку елементів. Два винятки (сума угоди,
статус) не мають жодних стабільних атрибутів у розмітці Playerok, тож їхні
селектори винесено окремо сюди: якщо сайт зміниться, достатньо поправити
значення саме тут, не чіпаючи логіку в orders.py.
"""

from __future__ import annotations

import re

# Список продажів (/profile/<username>/sales): кожна картка замовлення —
# посилання на сторінку угоди.
ORDER_CARD_LINK = 'a[href^="/deal/"]'

# Сторінка угоди (/deal/<id>).
CHAT_LINK = 'a[href^="/chats/"]'
PROFILE_LINK = 'a[href^="/profile/"]'
PRODUCT_LINK = 'a[href^="/products/"]'

# Посилання на покупця і на чат з ним лежать в одному <ul> — це відрізняє
# посилання на покупця від посилання "Профіль" у шапці сайту, яке веде на
# профіль самого продавця, а не покупця.
#
# ПЕРЕВІРЕНО на реальному debug_order.html (2026-07-08): це справжній тег
# <ul>, БЕЗ явного атрибута role="list" в HTML — раніше тут стояв XPath
# ancestor::*[@role="list"], що спирався на роль з accessibility tree
# (браузер обчислює її сам для <ul>), а не на реальний HTML-атрибут, тому
# ніколи нічого не знаходив (0 матчів). Тег <ul> — стабільна структурна
# ознака цього самого блоку, а не вгадана деталь верстки.
BUYER_LIST_ANCESTOR_XPATH = "ancestor::ul[1]"

# Сума угоди показана простим текстом із символом "₽" без жодних атрибутів.
AMOUNT_TEXT_PATTERN = re.compile(r"\d[\d\s]*\s*₽")

# Статус угоди — текстовий блок за два елементи перед <ul> (покупець/чат),
# без стабільних атрибутів. Прив'язка йде до найближчого <ul> з посиланням на
# чат (а не до абсолютної позиції на сторінці), щоб не залежати від решти
# розмітки над ним. Той самий фікс, що й для BUYER_LIST_ANCESTOR_XPATH: тег
# <ul>, а не role="list".
STATUS_XPATH = (
    'xpath=(//ul[.//a[starts-with(@href,"/chats/")]])[1]' "/preceding-sibling::*[2]"
)
